import { readFile, writeFile, appendFile } from 'node:fs/promises';
import { parseReleaseTag } from './release-version.mjs';
const { version, build, iosBuild, channel } = parseReleaseTag(process.env.RELEASE_TAG || process.env.GITHUB_REF_NAME || 'v1.0.0-beta.1');
const env = `APP_VERSION=${version}\nBUILD_NUMBER=${build}\nIOS_BUILD_NUMBER=${iosBuild}\nRELEASE_CHANNEL=${channel}\n`;
if (process.env.GITHUB_ENV) await appendFile(process.env.GITHUB_ENV, env);
if (process.env.GITHUB_OUTPUT) await appendFile(process.env.GITHUB_OUTPUT, `version=${version}\nbuild=${build}\nios_build=${iosBuild}\nchannel=${channel}\n`);
const file = 'ios/App/App.xcodeproj/project.pbxproj';
let pbx = await readFile(file, 'utf8');
pbx = pbx.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${version};`).replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${iosBuild};`);
await writeFile(file, pbx);
console.log(env);
